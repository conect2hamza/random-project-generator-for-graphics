	/**
	 * Copy the sprite symbols referenced by <use> into the clone.
	 *
	 * A serialised fragment has no access to the page's sprite, so any icon
	 * left as a reference would simply vanish from the export.
	 *
	 * @param {HTMLElement} clone Cloned subtree.
	 */
	function inlineIcons( clone ) {
		Array.prototype.forEach.call( clone.querySelectorAll( 'svg use' ), function ( use ) {
			var href = use.getAttribute( 'href' ) || use.getAttribute( 'xlink:href' ) || '';
			var symbol = href.charAt( 0 ) === '#' ? document.getElementById( href.slice( 1 ) ) : null;
			var svg = use.parentNode;

			if ( use.parentNode ) {
				use.parentNode.removeChild( use );
			}

			if ( ! symbol || ! svg ) {
				return;
			}

			if ( symbol.getAttribute( 'viewBox' ) ) {
				svg.setAttribute( 'viewBox', symbol.getAttribute( 'viewBox' ) );
			}

			Array.prototype.forEach.call( symbol.childNodes, function ( child ) {
				svg.appendChild( child.cloneNode( true ) );
			} );
		} );
	}

	/**
	 * Collect this plugin's own stylesheet text.
	 *
	 * Same-origin rules can be read straight from the CSSOM, which avoids a
	 * network request and keeps the export working offline.
	 *
	 * @return {string}
	 */
	function collectCss() {
		var css = '';

		Array.prototype.forEach.call( document.styleSheets, function ( sheet ) {
			var href = sheet.href || '';

			if ( href && href.indexOf( 'design-project-generator' ) === -1 ) {
				return;
			}

			var rules;

			try {
				rules = sheet.cssRules;
			} catch ( e ) {
				// A cross-origin sheet cannot be read; that is expected.
				return;
			}

			if ( ! rules ) {
				return;
			}

			Array.prototype.forEach.call( rules, function ( rule ) {
				if ( ! rule.cssText ) {
					return;
				}

				if ( ! href && rule.cssText.indexOf( 'dpg' ) === -1 ) {
					return;
				}

				css += rule.cssText + '\n';
			} );
		} );

		return css;
	}

	/**
	 * Rasterise the export area.
	 *
	 * @param {HTMLElement} area    Element to capture.
	 * @param {Object}      options width, quality.
	 * @return {Promise<Object>} Resolves with blob and scaled flag.
	 */
	function toPng( area, options ) {
		options = options || {};

		var targetWidth = options.width || parseInt( settings.pngWidth, 10 ) || 1920;
		var rect = area.getBoundingClientRect();
		var width = Math.max( 1, Math.ceil( rect.width ) );
		var height = Math.max( 1, Math.ceil( area.scrollHeight || rect.height ) );

		var clone = area.cloneNode( true );

		inlineIcons( clone );

		// The clone is laid out on its own, so pin the width it was measured
		// at and let the height run to the full content, not the viewport.
		clone.style.width = width + 'px';
		clone.style.height = 'auto';
		clone.style.margin = '0';
		clone.style.maxWidth = 'none';

		var scale = targetWidth / width;
		var maxDimension = 16384;
		var scaled = false;

		// Browsers refuse to allocate canvases beyond a few thousand pixels in
		// either direction. A very tall brief is scaled to fit rather than
		// silently producing a blank image.
		if ( height * scale > maxDimension ) {
			scale = maxDimension / height;
			scaled = true;
		}

		if ( width * scale > maxDimension ) {
			scale = maxDimension / width;
			scaled = true;
		}

		var css = collectCss();
		var wrapper = document.createElement( 'div' );

		wrapper.setAttribute( 'xmlns', 'http://www.w3.org/1999/xhtml' );
		wrapper.style.width = width + 'px';
		wrapper.style.background = '#ffffff';
		wrapper.appendChild( clone );

		var svg =
			'<svg xmlns="http://www.w3.org/2000/svg" width="' + width + '" height="' + height + '">' +
			'<foreignObject x="0" y="0" width="100%" height="100%">' +
			'<style>' + css.replace( /<\//g, '<\\/' ) + '</style>' +
			new XMLSerializer().serializeToString( wrapper ) +
			'</foreignObject></svg>';

		return new Promise( function ( resolve, reject ) {
			var image = new Image();
			var url = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent( svg );

			image.onload = function () {
				var canvas = document.createElement( 'canvas' );

				canvas.width = Math.max( 1, Math.round( width * scale ) );
				canvas.height = Math.max( 1, Math.round( height * scale ) );

				var context = canvas.getContext( '2d' );

				context.fillStyle = '#ffffff';
				context.fillRect( 0, 0, canvas.width, canvas.height );
				context.drawImage( image, 0, 0, canvas.width, canvas.height );

				canvas.toBlob( function ( blob ) {
					if ( blob ) {
						resolve( { blob: blob, scaled: scaled } );
					} else {
						reject( new Error( 'canvas' ) );
					}
				}, 'image/png' );
			};

			image.onerror = function () {
				reject( new Error( 'svg' ) );
			};

			image.src = url;
		} );
	}

